// Générateur automatique pour 2027 et 2028
export function generateSchoolHolidaysForYear(year: number): SchoolHolidayPeriod[] {
  if (year === 2026) return INITIAL_SCHOOL_HOLIDAYS_2026;

  const yearDiff = year - 2026;
  return INITIAL_SCHOOL_HOLIDAYS_2026.map((h) => {
    // Décalage calendrier annuel (+364 jours pour préserver le jour de semaine)
    const startObj = new Date(h.startDate);
    startObj.setFullYear(startObj.getFullYear() + yearDiff);
    const endObj = new Date(h.endDate);
    endObj.setFullYear(endObj.getFullYear() + yearDiff);

    const startStr = startObj.toISOString().split('T')[0];
    const endStr = endObj.toISOString().split('T')[0];

    return {
      ...h,
      id: `${h.id.replace('2026', String(year))}`,
      year,
      startDate: startStr,
      endDate: endStr,
      isOfficial: year === 2027 ? true : false,
      notes: year === 2028 ? 'Dates prévisionnelles basées sur la récurrence officielle' : h.notes,
    };
  });
}
