export function exportHolidaySegmentComparisonCSV(
  season: HolidaySeasonHistoricalSummary,
  hotelName: string
): void {
  const headers = [
    'Période Vacances',
    'Segment Clientèle',
    'Occ % Année N (2026)',
    'Occ % N-1 (2025)',
    'Occ % N-2 (2024)',
    'Delta Occ vs N-1 (pts)',
    'ADR € Année N (2026)',
    'ADR € N-1 (2025)',
    'ADR € N-2 (2024)',
    'Delta ADR vs N-1 (%)',
    'RevPAR € N',
    'RevPAR € N-1',
    'RevPAR € N-2',
    'Nuitées N',
    'CA Hébergement N (€)',
    'Part de Marché Segment (%)',
    'Durée Moyenne Séjour (ALOS nuits)',
    'TO % Hors Vacances (Base)',
    'ADR € Hors Vacances (Base)',
    'Observation Yield RM',
    'Recommandation Stratégique',
  ];

  const rows = season.segments.map((s) => {
    const meta = CLIENT_SEGMENTS.find((m) => m.key === s.segmentKey);
    const label = meta ? meta.label : s.segmentKey;
    const deltaOcc = (s.occupancyN - s.occupancyN1).toFixed(1);
    const deltaAdrPct = (((s.adrN - s.adrN1) / s.adrN1) * 100).toFixed(1);

    return [
      `"${season.name}"`,
      `"${label}"`,
      `${s.occupancyN}%`,
      `${s.occupancyN1}%`,
      `${s.occupancyN2}%`,
      `+${deltaOcc} pts`,
      `${s.adrN} €`,
      `${s.adrN1} €`,
      `${s.adrN2} €`,
      `+${deltaAdrPct}%`,
      `${s.revParN} €`,
      `${s.revParN1} €`,
      `${s.revParN2} €`,
      s.roomNightsN,
      `${s.revenueN} €`,
      `${s.shareOfRevenueN}%`,
      `${s.alosN} nuits`,
      `${s.baselineRegularOcc}%`,
      `${s.baselineRegularADR} €`,
      `"${s.yieldObservation.replace(/"/g, '""')}"`,
      `"${s.recommendedAction.replace(/"/g, '""')}"`,
    ];
  });

  const csvContent = [headers.join(';'), ...rows.map((row) => row.join(';'))].join('\n');
  const blob = new Blob(['\uFEFF' + csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute(
    'download',
    `analyse_vacances_scolaires_segments_${season.periodId}_${hotelName.toLowerCase().replace(/\s+/g, '_')}.csv`
  );
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}
